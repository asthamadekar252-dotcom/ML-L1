k_values=list(range(1,21))

train_accuracy=[]
test_accuracy=[]

for k in k_values:
    model=KNeighborsClassifier(n_neighbors=k)
    model.fit(X_train_scaled,y_train)
    train_accuracy.append(model.score(X_train_scaled,y_train))
    test_accuracy.append(model.score(X_test_scaled,y_test))

plt.figure(figsize=(10,6))

plt.plot(k_values,train_accuracy,marker="o",label="Training Accuracy")
plt.plot(k_values,test_accuracy,marker="x",label="Testing Accuracy")

plt.xlabel("Number of neighbors (K)")
plt.ylabel("Accuracy")
plt.title("KNN Accuracy vs K")
plt.xticks(k_values)
plt.legend()

plt.show()

cv=StratifiedKFold(n_splits=5,shuffle=True,random_state=42)
cv_scores=[]
k_values=list(range(1,21))

for k in k_values:
    model=KNeighborsClassifier(n_neighbors=k)
    scores=cross_val_score(model,X_train_scaled,y_train,cv=cv,scoring="accuracy")
    cv_scores.append(scores.mean())

plt.figure(figsize=(10,6))

plt.plot(range(1,21),cv_scores,marker="o")

plt.xlabel("K")
plt.ylabel("Mean VS Accuracy")
plt.title("KNN: K VS 5-Fold Cross-validation accuracy")
plt.xticks(range(1,21))

plt.show()

best_k_cv = np.argmax(cv_scores) + 1

print(f"Best K value based on 5-fold CV: {best_k_cv}")
print("Best CV Accuracy: ", max(cv_scores))

param_grid={"n_neighbors": list(range(3,21,2)),"weights":["uniform","distance"],

            "metric":["euclidean","manhattan","minkowski"],

            "p":[1,2]
}

